-- Screen design per program (current version only). Created by the basekit account; no existing table is altered (ADR 040/041).
CREATE TABLE BSDSCRN (
    SCREEN_DESIGN_ID VARCHAR(60) PRIMARY KEY,
    PROJECT_ID VARCHAR(50) NOT NULL,
    PROGRAM_ID VARCHAR(50) NOT NULL,
    PROGRAM_VERSION BIGINT,
    DESIGN_STATUS VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    SCREEN_TYPE VARCHAR(30) NOT NULL,
    DESIGN_JSON TEXT NOT NULL,
    VERSION BIGINT NOT NULL DEFAULT 1,
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DEL_YN CHAR(1) NOT NULL DEFAULT 'N',
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(50) NOT NULL DEFAULT 'system',
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(50) NOT NULL DEFAULT 'system',
    CONSTRAINT UQ_BSDSCRN_PROGRAM UNIQUE (PROGRAM_ID),
    CONSTRAINT CK_BSDSCRN_STATUS CHECK (DESIGN_STATUS IN ('DRAFT','CONFIRMED')),
    CONSTRAINT CK_BSDSCRN_USE_YN CHECK (USE_YN IN ('Y','N')),
    CONSTRAINT CK_BSDSCRN_DEL_YN CHECK (DEL_YN IN ('Y','N'))
);
CREATE INDEX IX_BSDSCRN_PROJECT ON BSDSCRN(PROJECT_ID);

COMMENT ON TABLE BSDSCRN IS '화면 설계 | BaseKit Standard Design Screen Design | 프로그램 1건당 1건의 화면(UI) 설계 현재 버전. 상세는 DESIGN_JSON.';
COMMENT ON COLUMN BSDSCRN.SCREEN_DESIGN_ID IS '화면설계ID: 서버가 SDSC-UUID 형식으로 생성';
COMMENT ON COLUMN BSDSCRN.PROJECT_ID IS '프로젝트ID: BSDPROJ 프로젝트 식별자';
COMMENT ON COLUMN BSDSCRN.PROGRAM_ID IS '프로그램ID: BSDGPROG 프로그램 식별자, 프로그램당 1건';
COMMENT ON COLUMN BSDSCRN.PROGRAM_VERSION IS '기준 프로그램 버전: 저장 시점의 BSDGPROG.VERSION(참고용)';
COMMENT ON COLUMN BSDSCRN.DESIGN_STATUS IS '설계상태: DRAFT 초안, CONFIRMED 확정';
COMMENT ON COLUMN BSDSCRN.SCREEN_TYPE IS '화면 유형: GRID_DETAIL 등';
COMMENT ON COLUMN BSDSCRN.DESIGN_JSON IS '설계(JSON): 검색조건·그리드 컬럼·상세 입력항목·Action';
COMMENT ON COLUMN BSDSCRN.VERSION IS '버전: 낙관적 잠금 버전, 저장·확정마다 증가';
COMMENT ON COLUMN BSDSCRN.USE_YN IS '사용여부: Y/N';
COMMENT ON COLUMN BSDSCRN.DEL_YN IS '삭제여부: 논리 삭제 여부 Y/N';
COMMENT ON COLUMN BSDSCRN.REG_DT IS '등록일시: 최초 등록 일시';
COMMENT ON COLUMN BSDSCRN.REG_BY IS '등록자: 최초 등록 사용자';
COMMENT ON COLUMN BSDSCRN.MOD_DT IS '수정일시: 최종 수정 일시';
COMMENT ON COLUMN BSDSCRN.MOD_BY IS '수정자: 최종 수정 사용자';
