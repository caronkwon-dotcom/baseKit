-- Registers every project ID that server tables already reference so existing projects show up in the master.
-- Name defaults to the ID; customer and period stay empty until someone fills them in. Safe to run again.
INSERT INTO BSDPROJ (PROJECT_ID, PROJECT_NAME)
SELECT S.PROJECT_ID, S.PROJECT_ID
FROM (
    SELECT PROJECT_ID FROM BSDRREQ
    UNION SELECT PROJECT_ID FROM BSDRGRP
    UNION SELECT PROJECT_ID FROM BSDGPROG
    UNION SELECT PROJECT_ID FROM BSDPGANL
    UNION SELECT PROJECT_ID FROM BSDPMSET
    UNION SELECT PROJECT_ID FROM BSDPMENU
    UNION SELECT PROJECT_ID FROM BSDRANLS
    UNION SELECT PROJECT_ID FROM BSDAANLS
) S
WHERE S.PROJECT_ID IS NOT NULL AND S.PROJECT_ID <> ''
  AND NOT EXISTS (SELECT 1 FROM BSDPROJ P WHERE P.PROJECT_ID = S.PROJECT_ID);
