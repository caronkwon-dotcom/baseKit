-- COMMON-003: Role 기준 Runtime 권한 모델
-- 권한 기준: ROLE × PROGRAM (프로그램 접근) + ROLE × PROGRAM × BUTTON_GROUP (버튼그룹/액션 접근)
-- USER→ROLE 매핑은 이번 범위에서 제외한다.
-- 기존 BSYBTGP / BSYPREP / BSYPROG / BSYMENU 구조는 변경하지 않는다.

CREATE TABLE BSYROLE (
    ROLE_ID VARCHAR(50) PRIMARY KEY,
    ROLE_CODE VARCHAR(100) NOT NULL,
    ROLE_NAME VARCHAR(100) NOT NULL,
    DESCRIPTION VARCHAR(500),
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DEL_YN CHAR(1) NOT NULL DEFAULT 'N',
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(50) NOT NULL,
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(50) NOT NULL,
    CONSTRAINT UK_BSYROLE_ROLE_CODE UNIQUE (ROLE_CODE),
    CONSTRAINT CK_BSYROLE_USE_YN CHECK (USE_YN IN ('Y', 'N')),
    CONSTRAINT CK_BSYROLE_DEL_YN CHECK (DEL_YN IN ('Y', 'N'))
);

CREATE INDEX IX_BSYROLE_USE_YN ON BSYROLE (USE_YN);

-- Role → Program: 해당 Role이 접근할 수 있는 Program (메뉴 노출/실행 권한)
CREATE TABLE BSYROLEPROG (
    ROLE_ID VARCHAR(50) NOT NULL REFERENCES BSYROLE (ROLE_ID),
    PROGRAM_ID VARCHAR(50) NOT NULL REFERENCES BSYPROG (PROGRAM_ID),
    ALLOW_YN CHAR(1) NOT NULL DEFAULT 'Y',
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(50) NOT NULL,
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(50) NOT NULL,
    PRIMARY KEY (ROLE_ID, PROGRAM_ID),
    CONSTRAINT CK_BSYROLEPROG_ALLOW_YN CHECK (ALLOW_YN IN ('Y', 'N'))
);

CREATE INDEX IX_BSYROLEPROG_PROGRAM ON BSYROLEPROG (PROGRAM_ID);

-- Role → ButtonGroup: Program 내부 ButtonGroup(액션 그룹) 접근 권한
CREATE TABLE BSYROLEBTGP (
    ROLE_ID VARCHAR(50) NOT NULL REFERENCES BSYROLE (ROLE_ID),
    PROGRAM_ID VARCHAR(50) NOT NULL REFERENCES BSYPROG (PROGRAM_ID),
    GROUP_CODE VARCHAR(100) NOT NULL,
    ALLOW_YN CHAR(1) NOT NULL DEFAULT 'Y',
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(50) NOT NULL,
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(50) NOT NULL,
    PRIMARY KEY (ROLE_ID, PROGRAM_ID, GROUP_CODE),
    CONSTRAINT FK_BSYROLEBTGP_BTGP FOREIGN KEY (PROGRAM_ID, GROUP_CODE) REFERENCES BSYBTGP (PROGRAM_ID, GROUP_CODE),
    CONSTRAINT CK_BSYROLEBTGP_ALLOW_YN CHECK (ALLOW_YN IN ('Y', 'N'))
);

CREATE INDEX IX_BSYROLEBTGP_PROGRAM ON BSYROLEBTGP (PROGRAM_ID);

