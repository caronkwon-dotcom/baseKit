-- Additive only. Apply to the shared PostgreSQL separately after SD review.
CREATE TABLE BSDRCHG (
 REQUIREMENT_ID VARCHAR(50) NOT NULL REFERENCES BSDRREQ(REQUIREMENT_ID),
 REQUIREMENT_REVISION BIGINT NOT NULL,
 BASE_REVISION BIGINT NOT NULL,
 VERSION BIGINT NOT NULL DEFAULT 1,
 CHANGE_STATE VARCHAR(20) NOT NULL CHECK (CHANGE_STATE IN ('DRAFT','CONFIRMED','CANCELLED')),
 CHANGE_REASON VARCHAR(2000) NOT NULL,
 SNAPSHOT TEXT NOT NULL,
 CREATED_BY VARCHAR(200) NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(REQUIREMENT_ID,REQUIREMENT_REVISION)
);
-- Portable uniqueness: only an open draft has a non-null OPEN_REQUIREMENT_ID.
ALTER TABLE BSDRCHG ADD COLUMN OPEN_REQUIREMENT_ID VARCHAR(50) UNIQUE;
ALTER TABLE BSDRCHG ADD CONSTRAINT CK_BSDRCHG_OPEN CHECK (
 (CHANGE_STATE='DRAFT' AND OPEN_REQUIREMENT_ID=REQUIREMENT_ID AND OPEN_REQUIREMENT_ID IS NOT NULL)
 OR (CHANGE_STATE<>'DRAFT' AND OPEN_REQUIREMENT_ID IS NULL));
CREATE TABLE BSDRRATT (
 REQUIREMENT_ID VARCHAR(50) NOT NULL REFERENCES BSDRREQ(REQUIREMENT_ID),
 REQUIREMENT_REVISION BIGINT NOT NULL,
 ATTACHMENT_ID VARCHAR(50) NOT NULL REFERENCES BSDRATCH(ATTACHMENT_ID),
 PRIMARY KEY(REQUIREMENT_ID,REQUIREMENT_REVISION,ATTACHMENT_ID)
);
INSERT INTO BSDRRATT(REQUIREMENT_ID,REQUIREMENT_REVISION,ATTACHMENT_ID)
 SELECT R.REQUIREMENT_ID,R.REQUIREMENT_REVISION,A.ATTACHMENT_ID FROM BSDRREQ R JOIN BSDRATCH A ON A.REQUIREMENT_ID=R.REQUIREMENT_ID;
CREATE TABLE BSDRDEVT (
 REQUIREMENT_ID VARCHAR(50) PRIMARY KEY REFERENCES BSDRREQ(REQUIREMENT_ID),
 DISCARD_REASON VARCHAR(2000) NOT NULL,
 DISCARDED_BY VARCHAR(200) NOT NULL,
 DISCARDED_AT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
