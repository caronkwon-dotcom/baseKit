-- BK-COMMON-REQ-001: common document numbering rules, counters and immutable issue ledger.
CREATE TABLE IF NOT EXISTS BKDOCSEQ_RULE (
    RULE_KEY VARCHAR(80) NOT NULL,
    RULE_VERSION INTEGER NOT NULL,
    RULE_NAME VARCHAR(160) NOT NULL,
    PREFIX VARCHAR(40) NOT NULL,
    DATE_FORMAT VARCHAR(12) NOT NULL DEFAULT 'NONE',
    SEQUENCE_LENGTH INTEGER NOT NULL,
    START_VALUE BIGINT NOT NULL,
    INCREMENT_VALUE BIGINT NOT NULL,
    RESET_CYCLE VARCHAR(10) NOT NULL,
    SCOPE_TYPE VARCHAR(12) NOT NULL,
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DESCRIPTION VARCHAR(500),
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(80) NOT NULL DEFAULT 'system',
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(80) NOT NULL DEFAULT 'system',
    PRIMARY KEY (RULE_KEY, RULE_VERSION),
    CHECK (RULE_VERSION > 0),
    CHECK (SEQUENCE_LENGTH BETWEEN 1 AND 18),
    CHECK (START_VALUE > 0),
    CHECK (INCREMENT_VALUE > 0),
    CHECK (RESET_CYCLE IN ('NONE', 'YEAR', 'MONTH')),
    CHECK (SCOPE_TYPE IN ('GLOBAL', 'MODULE', 'PROJECT')),
    CHECK (USE_YN IN ('Y', 'N')),
    CHECK (DATE_FORMAT IN ('NONE', 'YYYY', 'YYYYMM'))
);

CREATE TABLE IF NOT EXISTS BKDOCSEQ_COUNTER (
    RULE_KEY VARCHAR(80) NOT NULL,
    RULE_VERSION INTEGER NOT NULL,
    SCOPE_KEY VARCHAR(160) NOT NULL,
    PERIOD_KEY VARCHAR(8) NOT NULL,
    LAST_VALUE BIGINT NOT NULL,
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (RULE_KEY, RULE_VERSION, SCOPE_KEY, PERIOD_KEY),
    FOREIGN KEY (RULE_KEY, RULE_VERSION) REFERENCES BKDOCSEQ_RULE (RULE_KEY, RULE_VERSION)
);

CREATE TABLE IF NOT EXISTS BKDOCSEQ_ISSUE (
    ISSUE_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    RULE_KEY VARCHAR(80) NOT NULL,
    RULE_VERSION INTEGER NOT NULL,
    SCOPE_KEY VARCHAR(160) NOT NULL,
    PERIOD_KEY VARCHAR(8) NOT NULL,
    SEQUENCE_VALUE BIGINT NOT NULL,
    DOCUMENT_NUMBER VARCHAR(300) NOT NULL,
    IDEMPOTENCY_KEY VARCHAR(160) NOT NULL,
    REQUEST_FINGERPRINT VARCHAR(128) NOT NULL,
    ISSUE_STATUS VARCHAR(12) NOT NULL DEFAULT 'RESERVED',
    BUSINESS_REF VARCHAR(200),
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_BKDOCSEQ_ISSUE_RULE FOREIGN KEY (RULE_KEY, RULE_VERSION)
        REFERENCES BKDOCSEQ_RULE (RULE_KEY, RULE_VERSION),
    CONSTRAINT UQ_BKDOCSEQ_ISSUE_NUMBER UNIQUE (DOCUMENT_NUMBER),
    CONSTRAINT UQ_BKDOCSEQ_ISSUE_COUNTER UNIQUE (RULE_KEY, RULE_VERSION, SCOPE_KEY, PERIOD_KEY, SEQUENCE_VALUE),
    CONSTRAINT UQ_BKDOCSEQ_ISSUE_IDEMPOTENCY UNIQUE (RULE_KEY, IDEMPOTENCY_KEY),
    CHECK (ISSUE_STATUS IN ('RESERVED', 'COMPLETED', 'ABANDONED'))
);

CREATE INDEX IF NOT EXISTS IX_BKDOCSEQ_ISSUE_HISTORY
    ON BKDOCSEQ_ISSUE (RULE_KEY, RULE_VERSION, REG_DT DESC, ISSUE_ID);

