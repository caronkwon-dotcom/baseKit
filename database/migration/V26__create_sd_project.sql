-- Project master for Standard Design. Until now the project data lived only in each browser's localStorage.
CREATE TABLE BSDPROJ (
    PROJECT_ID VARCHAR(50) PRIMARY KEY,
    PROJECT_NAME VARCHAR(200) NOT NULL,
    CUSTOMER_NAME VARCHAR(200) NOT NULL DEFAULT '',
    DESCRIPTION TEXT NOT NULL DEFAULT '',
    STATUS VARCHAR(30) NOT NULL DEFAULT 'DRAFT',
    START_DATE DATE,
    END_DATE DATE,
    VERSION BIGINT NOT NULL DEFAULT 1,
    USE_YN CHAR(1) NOT NULL DEFAULT 'Y',
    DEL_YN CHAR(1) NOT NULL DEFAULT 'N',
    REG_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    REG_BY VARCHAR(50) NOT NULL DEFAULT 'system',
    MOD_DT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    MOD_BY VARCHAR(50) NOT NULL DEFAULT 'system',
    CONSTRAINT CK_BSDPROJ_STATUS CHECK (STATUS IN ('DRAFT','IN_PROGRESS','REVIEW','APPROVED')),
    CONSTRAINT CK_BSDPROJ_USE_YN CHECK (USE_YN IN ('Y','N')),
    CONSTRAINT CK_BSDPROJ_DEL_YN CHECK (DEL_YN IN ('Y','N')),
    CONSTRAINT CK_BSDPROJ_PERIOD CHECK (START_DATE IS NULL OR END_DATE IS NULL OR START_DATE <= END_DATE)
);
CREATE INDEX IX_BSDPROJ_NAME ON BSDPROJ(PROJECT_NAME);
