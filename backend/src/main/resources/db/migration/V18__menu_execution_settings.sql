-- JSON/Module Manifest menuKey is the immutable join key; this table owns execution settings only.
CREATE TABLE BSMEXCFG (
 MENU_ID VARCHAR(160) PRIMARY KEY,
 EXECUTION_TYPE VARCHAR(10) NOT NULL DEFAULT 'INNER' CHECK (EXECUTION_TYPE IN ('INNER', 'WINDOW')),
 DESIGN_TYPE VARCHAR(10) NOT NULL DEFAULT 'BASEKIT' CHECK (DESIGN_TYPE IN ('BASEKIT', 'LINEAR'))
);
