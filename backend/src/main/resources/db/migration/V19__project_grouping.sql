-- Additive workspace storage; existing requirement/group/analysis history is untouched.
CREATE TABLE BSDPGANL (
 ANALYSIS_ID VARCHAR(50) PRIMARY KEY,
 PROJECT_ID VARCHAR(50) NOT NULL,
 REQUEST_ID VARCHAR(100) NOT NULL,
 ANALYSIS_TYPE VARCHAR(30) NOT NULL DEFAULT 'PROJECT_GROUPING' CHECK (ANALYSIS_TYPE='PROJECT_GROUPING'),
 STATUS VARCHAR(30) NOT NULL,
 REQUEST_JSON TEXT NOT NULL,
 DRAFT_JSON TEXT,
 VERSION BIGINT NOT NULL DEFAULT 0,
 ERROR_MESSAGE VARCHAR(500),
 CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 DEADLINE_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 COMPLETED_AT TIMESTAMP WITH TIME ZONE,
 UNIQUE(PROJECT_ID,REQUEST_ID)
);
CREATE TABLE BSDPGRAW (
 ANALYSIS_ID VARCHAR(50) NOT NULL REFERENCES BSDPGANL(ANALYSIS_ID),
 CHUNK_NO INTEGER NOT NULL,
 RESPONSE_RAW_JSON TEXT NOT NULL,
 MODEL_NAME VARCHAR(200),
 HTTP_STATUS INTEGER,
 PRIMARY KEY(ANALYSIS_ID,CHUNK_NO)
);
CREATE TABLE BSDPGLNK (
 ANALYSIS_ID VARCHAR(50) NOT NULL REFERENCES BSDPGANL(ANALYSIS_ID),
 DRAFT_GROUP_ID VARCHAR(50) NOT NULL,
 REQUIREMENT_GROUP_ID VARCHAR(50) NOT NULL REFERENCES BSDRGRP(REQUIREMENT_GROUP_ID),
 EVIDENCE_JSON TEXT NOT NULL,
 PRIMARY KEY(ANALYSIS_ID,DRAFT_GROUP_ID)
);
CREATE INDEX IX_BSDPGANL_PROJECT ON BSDPGANL(PROJECT_ID,CREATED_AT);
